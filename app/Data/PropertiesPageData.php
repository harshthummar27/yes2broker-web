    public static function findBySlug(string $slug): ?array
    {
        foreach (self::properties() as $property) {
            if ($property['slug'] === $slug) {
                return $property;
            }
        }

        return null;
    }

    public static function perPage(): int
    {
        return 30;
    }

    public static function paginate(int $page = 1, array $filters = []): array
    {
        $items = self::filter($filters);
        $offset = max(0, ($page - 1) * self::perPage());

        return array_slice($items, $offset, self::perPage());
    }

    public static function totalPages(array $filters = []): int
    {
        return max(1, (int) ceil(count(self::filter($filters)) / self::perPage()));
    }

    public static function totalCount(array $filters = []): int
    {
        return count(self::filter($filters));
    }

    public static function filter(array $filters = []): array
    {
        $items = self::properties();
        $filters = array_filter($filters, fn ($v) => $v !== null && $v !== '');

        if (! empty($filters['city'])) {
            $city = strtolower($filters['city']);
            $items = array_values(array_filter($items, function (array $property) use ($city) {
                $haystack = strtolower($property['location']);

                return $city === 'gandhinagar'
                    ? str_contains($haystack, 'gandhinagar')
                    : ! str_contains($haystack, 'gandhinagar');
            }));
        }

        if (! empty($filters['area'])) {
            $area = strtolower($filters['area']);
            $items = array_values(array_filter($items, fn (array $p) => str_contains(strtolower($p['location'].' '.$p['title']), $area)));
        }

        if (! empty($filters['type'])) {
            $typeMap = [
                'apartment' => 'bhk',
                'villa' => 'villa',
                'bungalow' => 'bungalow',
                'office' => 'office',
                'showroom' => 'showroom',
                'shop' => 'shop',
                'farmhouse' => 'farmhouse',
                'land' => 'plot',
            ];
            $needle = $typeMap[$filters['type']] ?? $filters['type'];
            $items = array_values(array_filter($items, fn (array $p) => str_contains(strtolower($p['bhk']), strtolower($needle))));
        }

        if (! empty($filters['budget'])) {
            $maxBudgetLakhs = HomePageData::budgetMaxLakhs($filters['budget']);

            if ($maxBudgetLakhs !== null) {
                $items = array_values(array_filter(
                    $items,
                    fn (array $p) => ($lakhs = self::priceMinLakhs($p['price'])) > 0 && $lakhs <= $maxBudgetLakhs
                ));
            }
        }

        return $items;
    }

    private static function priceMinLakhs(string $price): float
    {
        if (preg_match('/₹?\s*([\d.]+)\s*(Lakhs?|L\b|Cr)/i', $price, $m)) {
            $value = (float) $m[1];

            return str_contains(strtolower($m[2]), 'cr') ? $value * 100 : $value;
        }

        return 0;
    }
